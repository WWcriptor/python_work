str1 =  "He likes apples, and she does, too"

# 대문자로
str2 = str1.upper()
print(str1)
print(str2)

# 소문자로
str2 = str1.lower()
print(str1)
print(str2)

print("-"*20)

# 대문자 <-> 소문자
str2 = str1.swapcase()
print(str1)
print(str2)

print("-"*20)

#문장의 첫 글자만 대문자로
str3 = str2.capitalize()
print(str2)
print(str3)

print("-"*20)

#단어의 첫 글자를 대문자로
str2 = str1.title()
print(str1)
print(str2)