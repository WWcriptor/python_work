# 비교 연산자는 결과가 bool 형태로 출력
#< , > <=, >= 
# == : 같다 != : 같지 않다

num1 = int(input("첫 번째 정수 입력: "))
num2 = int(input("두 번쨰 정수 입력: "))

print(f"첫 번째 숫자가 두 번쨰 숫자보다 큰가? {num1>num2}")
print(f"첫 번째 숫자가 두 번쨰 숫자보다 크거나 같은가? {num1>=num2}")
print(f"첫 번째 숫자가 두 번쨰 숫자보다 작은가? {num1<num2}")
print(f"첫 번째 숫자가 두 번쨰 숫자보다 작거나 같은가? {num1<=num2}")
print(f"첫 번쨰 숫자가 두 번쨰 숫자와 같은가? {num1==num2}")
print(f"첫 번째 숫자가 두 번쨰 숫자와 같지 않은가? {num1!=num2}")